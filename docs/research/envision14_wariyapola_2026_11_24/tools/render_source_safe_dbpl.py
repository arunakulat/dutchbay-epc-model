class SourceSafeDbplFurniture(DbplFurniture):
    """Reuse the DBPL-01 print core while disclosing actual report provenance.

    The generic lender furniture's revision_source refers specifically to
    run_full_pipeline_v14 and is NOT truthful for this standalone R3 annex.
    """

    def as_doc(self):
        document = super().as_doc()
        document["revision_source"] = (
            "Generated by docs/research/envision14_wariyapola_2026_11_24/"
            "tools/render_source_safe_dbpl.py from conditional screening CSV/JSON; "
            "not emitted by the full lender financial pipeline; no human sign-off."
        )
        return document


def read_csv(relative: str) -> list[dict[str, str]]:
    with (PKG / relative).open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def E(value: object) -> str:
    return html.escape(str(value), quote=True)


def P(value: object) -> str:
    return "<p>" + E(value) + "</p>"


def H(value: str) -> str:
    return "<h2>" + E(value) + "</h2>"


def SUB(value: str) -> str:
    return "<h3>" + E(value) + "</h3>"


def table(headers: list[str], rows: list[tuple[object, ...]]) -> str:
    return (
        "<table><thead><tr>"
        + "".join("<th>" + E(x) + "</th>" for x in headers)
        + "</tr></thead><tbody>"
        + "".join(
            "<tr>" + "".join("<td>" + E(y) + "</td>" for y in row) + "</tr>"
            for row in rows
        )
        + "</tbody></table>"
    )


