#!/usr/bin/env python3
"""Hydra CLI: Blue Whale solar + BESS unit (array, land, PV yield, hourly BESS dispatch).

Reads ``conf/blue_whale_solar_bess.yaml`` and prints one JSON object (CLI-01, CLI-03):

* the module, string and table design, row pitch and ground coverage ratio, the land
  the unit needs, and whether it fits PR 1's placeholder lot
  (:mod:`analytics.gis.pv_array_layout`);
* the PV yield from the repository's producer
  (:func:`solar_resource.pv_producer.compute_solar_aep`) and its hourly series, checked
  to sum to the producer's annual energy;
* the hourly dispatch of the battery over the TMY year, its annual energy and revenue
  by rate, the degradation path, and the engine fields that represent the unit
  (:mod:`solar_resource.pv_bess_dispatch`).

Usage::

    .venv/bin/python scripts/run_blue_whale_solar_bess_v14.py
    .venv/bin/python scripts/run_blue_whale_solar_bess_v14.py \\
        output.hourly_csv=docs/blue_whale/pv_bess_hourly_tmy.csv \\
        output.layout_geojson=docs/blue_whale/pv_bess_layout_lot5b.geojson
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Dict, Mapping

import hydra
import yaml
from omegaconf import DictConfig, OmegaConf

from analytics.gis.pv_array_layout import (
    ArrayConfig,
    BessFootprintConfig,
    LandConfig,
    ModuleSpec,
    ShadingRuleConfig,
    SiteFitConfig,
    StringDesignConfig,
    as_dict,
    compact_land_area,
    design_string,
    equipment_area,
    fit_site,
    layout_feature_collection,
    row_pitch,
    site_geometry,
    size_array,
)
from analytics.gis.shadow_flicker import CoastalSetbackConfig, LocalFrame
from solar_resource.pv_bess_dispatch import (
    BessConfig,
    DispatchConfig,
    DispatchSeries,
    TariffConfig,
    WindBlock,
    degradation_path,
    dispatch,
    engine_representation,
    hourly_pv,
    summarise,
    with_array,
)
from solar_resource.pv_producer import compute_solar_aep

REPO_ROOT = Path(__file__).resolve().parents[1]

#: Relative agreement required between the hourly series and the producer's annual energy.
PARITY_TOLERANCE = 1e-9


def _repo_path(rel: str) -> Path:
    """Resolve a config path against the repository root."""
    p = Path(rel)
    return p if p.is_absolute() else REPO_ROOT / p


def _load_yaml(rel: str) -> Dict[str, Any]:
    """Read a YAML mapping from the repository."""
    data = yaml.safe_load(_repo_path(rel).read_text())
    if not isinstance(data, dict):
        raise TypeError(f"{rel} is not a YAML mapping")
    return data


def wind_block(scenario: Mapping[str, Any]) -> WindBlock:
    """The scenario's wind technology (kept unchanged by this unit)."""
    wind = scenario["generation"]["technologies"]["wind"]
    return WindBlock(
        capacity_mw=float(wind["capacity_mw"]),
        capacity_factor=float(wind["capacity_factor"]),
        degradation_pct=float(wind["degradation_pct"]),
    )


def _write_hourly_csv(
    path: Path, timestamps: Any, series: DispatchSeries, window_names: list[str]
) -> None:
    """Year-1 hourly dispatch as CSV (MW over one-hour steps, i.e. MWh per hour)."""
    names = {-1: "", **dict(enumerate(window_names))}
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as fh:
        fh.write(
            "# Blue Whale solar + BESS unit, year 1 (PV at the warranted year-1 factor), "
            "hourly over the frozen PVGIS TMY. Hour-start UTC labels; Asia/Colombo is "
            "UTC+05:30. MW over one hour = MWh. Generated by "
            "scripts/run_blue_whale_solar_bess_v14.py (conf/blue_whale_solar_bess.yaml).\n"
        )
        fh.write(
            "time_utc,pv_mw,charge_mw,pv_export_mw,discharge_mw,curtailed_mw,soc_mwh,window\n"
        )
        for i, t in enumerate(timestamps):
            k = int(series.window[i])
            label = names.get(k, str(k))
            row = [
                t.strftime("%Y-%m-%dT%H"),
                *(
                    f"{float(arr[i]):.4f}".rstrip("0").rstrip(".")
                    for arr in (
                        series.pv_mw,
                        series.charge_mw,
                        series.pv_export_mw,
                        series.discharge_mw,
                        series.curtailed_mw,
                        series.soc_end_mwh,
                    )
                ),
                label,
            ]
            fh.write(",".join(row) + "\n")


def run(cfg: Mapping[str, Any]) -> Dict[str, Any]:
    """Run the unit and return the JSON-ready result.

    Raises:
        RuntimeError: If the hourly PV series does not sum to the producer's energy.
    """
    module = ModuleSpec.from_mapping(cfg["module"])
    strings = design_string(
        module, StringDesignConfig.from_mapping(cfg["string_design"])
    )
    array = ArrayConfig.from_mapping(cfg["array"])
    sizing = size_array(module, strings, array)
    land = LandConfig.from_mapping(cfg["land"])
    bess = BessConfig.from_mapping(cfg["bess"])
    equipment = equipment_area(
        bess_power_mw=bess.power_mw,
        bess_energy_mwh=bess.energy_mwh,
        bess=BessFootprintConfig.from_mapping(cfg["bess_footprint"]),
        land=land,
    )

    # Site: PR 1's frame, lot, turbine and coastal setback.
    fit_cfg = SiteFitConfig.from_mapping(cfg["site_fit"])
    wind_siting = _load_yaml(fit_cfg.wind_siting_config)
    frame = LocalFrame(
        float(wind_siting["site"]["reference_lat_deg"]),
        float(wind_siting["site"]["reference_lon_deg"]),
    )
    coastal = CoastalSetbackConfig.from_mapping(wind_siting["coastal_setback"])
    site = site_geometry(
        json.loads(_repo_path(fit_cfg.site_geojson).read_text()),
        json.loads(_repo_path(fit_cfg.coastline_geojson).read_text()),
        frame,
    )
    ce = sum(p[0] for p in site.lot_ring) / len(site.lot_ring)
    cn = sum(p[1] for p in site.lot_ring) / len(site.lot_ring)
    lot_lon, lot_lat = frame.to_lon_lat(ce, cn)

    pitch = row_pitch(
        lat_deg=lot_lat,
        lon_deg=lot_lon,
        sizing=sizing,
        array=array,
        rule=ShadingRuleConfig.from_mapping(cfg["shading_rule"]),
    )
    area = compact_land_area(
        sizing=sizing, pitch=pitch, array=array, land=land, equipment=equipment
    )
    layout = fit_site(
        site,
        coastal=coastal,
        cfg=fit_cfg,
        sizing=sizing,
        pitch=pitch,
        array=array,
        land=land,
        equipment=equipment,
        required_fenced_area_m2=area.fenced_area_m2,
    )

    # PV yield: the producer, then its hourly series pinned to it.
    pv_cfg = cfg["pv_yield"]
    solar = with_array(
        pv_cfg["resource_solar"],
        dc_capacity_mw=sizing.dc_capacity_mw,
        dc_ac_ratio=sizing.dc_ac_ratio,
        tilt_deg=array.tilt_deg,
        azimuth_deg=array.azimuth_deg,
        gamma_pdc_per_c=module.temp_coeff_pmax_pct_per_c / 100.0,
    )
    aep = compute_solar_aep(solar)
    pv = hourly_pv(solar)
    gap = abs(pv.annual_mwh / 1000.0 - aep.annual_energy_gwh) / aep.annual_energy_gwh
    if gap > PARITY_TOLERANCE:
        raise RuntimeError(
            f"hourly PV sums to {pv.annual_mwh} MWh, producer {aep.annual_energy_gwh} GWh"
        )
    years = int(pv_cfg["degradation_years"])
    factors = [module.warranted_power_fraction(y) for y in range(1, years + 1)]

    # Dispatch.
    dcfg = DispatchConfig.from_mapping(cfg["dispatch"])
    tariff = TariffConfig.from_mapping(cfg["tariff"])
    year1 = dispatch(pv.ac_mw * factors[0], pv.timestamps_utc, bess, dcfg)
    summary = summarise(year1, bess, dcfg, tariff, year=1, pv_factor=factors[0])
    other_policy = "evening_need" if dcfg.charge_policy == "fill" else "fill"
    alt_cfg = DispatchConfig(
        timezone=dcfg.timezone,
        windows=dcfg.windows,
        export_limit_mw=dcfg.export_limit_mw,
        charge_policy=other_policy,
        cyclic_soc_tolerance_mwh=dcfg.cyclic_soc_tolerance_mwh,
        cyclic_soc_max_iterations=dcfg.cyclic_soc_max_iterations,
    )
    alt = summarise(
        dispatch(pv.ac_mw * factors[0], pv.timestamps_utc, bess, alt_cfg),
        bess,
        alt_cfg,
        tariff,
        year=1,
        pv_factor=factors[0],
    )
    path = degradation_path(pv, factors, bess, dcfg, tariff)

    # Engine representation against the scenario's (unchanged) wind block.
    ecfg = cfg["engine"]
    scenario = _load_yaml(str(ecfg["scenario"]))
    engine = engine_representation(
        path,
        wind=wind_block(scenario),
        capacity_mw=array.ac_capacity_mw,
        bess=bess,
        tariff=tariff,
    )

    out_cfg = cfg["output"]
    if out_cfg.get("hourly_csv"):
        _write_hourly_csv(
            _repo_path(str(out_cfg["hourly_csv"])),
            pv.timestamps_utc,
            year1,
            [w.name for w in dcfg.windows],
        )
    layout_doc = layout_feature_collection(
        layout, frame, required=sizing.tables, decimals=fit_cfg.geojson_decimals
    )
    if out_cfg.get("layout_geojson"):
        target = _repo_path(str(out_cfg["layout_geojson"]))
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(layout_doc, indent=1) + "\n")

    fit = as_dict(layout.fit)
    return {
        "model_version": (REPO_ROOT / "VERSION").read_text().strip(),
        "config": "conf/blue_whale_solar_bess.yaml",
        "placeholder_site": True,
        "caveat": (
            "The land fit depends on PR 1's placeholder lot (assumed square) and its "
            "OpenStreetMap coastline; no survey exists (input B03)."
        ),
        "module": {
            "name": module.name,
            "pmax_w": module.pmax_w,
            "area_m2": module.area_m2,
            "warranted_power_fraction": {str(y): f for y, f in enumerate(factors, 1)},
        },
        "strings": as_dict(strings),
        "array": as_dict(sizing),
        "row_pitch": as_dict(pitch),
        "lot_centroid": {"lat_deg": lot_lat, "lon_deg": lot_lon},
        "equipment": as_dict(equipment),
        "land": as_dict(area),
        "site_fit": fit,
        "pv_yield": {
            "producer_annual_energy_gwh": aep.annual_energy_gwh,
            "producer_capacity_factor_dc": aep.capacity_factor,
            "capacity_factor_ac": aep.annual_energy_gwh
            * 1000.0
            / (array.ac_capacity_mw * 8760.0),
            "specific_yield_kwh_per_kwp": aep.specific_yield_kwh_per_kwp,
            "poa_kwh_m2": aep.poa_kwh_m2,
            "ghi_kwh_m2": aep.ghi_kwh_m2,
            "hourly_sum_gwh": pv.annual_mwh / 1000.0,
            "hourly_parity_relative_gap": gap,
            "loss_factor": pv.loss_factor,
            "dc_clipped_mwh": float(pv.dc_clipped_mw.sum()),
            "peak_ac_mw": float(pv.ac_mw.max()),
            "year1_energy_gwh": aep.annual_energy_gwh * factors[0],
            "bifacial_modelled": bool(pv_cfg["bifacial_modelled"]),
            "turbine_shading_modelled": bool(pv_cfg["turbine_shading_modelled"]),
        },
        "dispatch": {
            "policy": dcfg.charge_policy,
            "initial_soc_mwh": year1.initial_soc_mwh,
            "cyclic_iterations": year1.iterations,
            "year1": as_dict(summary),
            "alternative_policy": {"policy": other_policy, "year1": as_dict(alt)},
        },
        "degradation_path": [
            {
                "year": a.year,
                "pv_factor": a.pv_factor,
                "pv_mwh": a.pv_mwh,
                "unit_export_mwh": a.unit_export_mwh,
                "priority_export_mwh": a.export_mwh_by_rate["priority"],
                "revenue_lkr": a.revenue_lkr,
            }
            for a in path
        ],
        "engine": as_dict(engine),
        "layout_features": len(layout_doc["features"]),
    }


@hydra.main(
    version_base="1.3", config_path="../conf", config_name="blue_whale_solar_bess"
)
def main(cfg: DictConfig) -> None:
    """Run the unit and print one JSON object.

    Args:
        cfg: Hydra-composed config.

    Raises:
        TypeError: If the config does not resolve to a mapping.
    """
    logging.disable(logging.INFO)
    raw: Any = OmegaConf.to_container(cfg, resolve=True)
    if not isinstance(raw, dict):
        raise TypeError("expected the Hydra config to resolve to a mapping")
    print(json.dumps(run(raw), sort_keys=True, allow_nan=False))


if __name__ == "__main__":
    main()
